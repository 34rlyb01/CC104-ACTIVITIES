class MathOper {
	
	public static void main(String EJY[]) {

	int n1 = 10;
	int n2 = 4;

	int Sum, Diff, Quot, Rem;

	Sum = n1 + n2;
	System.out.println("Sum is: " + Sum);

	Diff = n1 - n2;
	System.out.println("Difference is: " + Diff);

	Quot = n1 / n2;
	System.out.println("Quotient is: " + Quot);

	Rem = n1 % n2;
	System.out.println("Remainder is: " + Rem);
	}
}

